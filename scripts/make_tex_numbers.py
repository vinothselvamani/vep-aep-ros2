"""Turn results.json + ros2_summary.json into LaTeX macros and tables (no hand-typed numbers).

Usage: python make_tex_numbers.py <eval_outdir> <ros_outdir> <paper_dir>
"""
import json

import numpy as np
import os
import sys

ev_dir, ros_dir, out = sys.argv[1:4]
r = json.load(open(os.path.join(ev_dir, "results.json")))
s = json.load(open(os.path.join(ros_dir, "ros2_summary.json")))
M = {}


def f(x, n=1):
    return f"{x:.{n}f}"


M["Ntrials"] = r["n_trials"]; M["Nch"] = r["n_ch"]; M["Fs"] = f(r["fs"], 2); M["Dur"] = f(r["duration_s"] / 60, 1)
for code, name in zip("1234", ["NLA", "NRA", "NLV", "NRV"]):
    M[name] = r["counts"][code]
for k, name in [("AEP_N1", "AN"), ("AEP_P2", "AP"), ("VEP_P1", "VP"), ("VEP_N1", "VN")]:
    M[name + "lat"] = f(r["components"][k]["lat_ms"], 0); M[name + "amp"] = f(r["components"][k]["amp_uV"], 1)
cv = r["cv"]
key = {"modality (AEP vs VEP)": "Mod", "4-class (LA/RA/LV/RV)": "Four", "aud. laterality (L vs R)": "AudLat",
       "vis. laterality (L vs R)": "VisLat"}
mkey = {"xDAWN-LDA": "X", "Cluster-LDA": "C", "Template": "T"}
for t, tk in key.items():
    M["Chance" + tk] = f(r["chance"][t] * 100)
    for m, mk in mkey.items():
        M[f"Acc{tk}{mk}"] = f(cv[t][m]["acc_mean"] * 100); M[f"Sd{tk}{mk}"] = f(cv[t][m]["acc_sd"] * 100)
        M[f"Kap{tk}{mk}"] = f(cv[t][m]["kappa_mean"], 2)
        if "auc_mean" in cv[t][m]:
            M[f"Auc{tk}{mk}"] = f(cv[t][m]["auc_mean"], 3)
M["PermP"] = f"{r['perm_modality']['p']:.3f}"; M["Nperm"] = r["perm_modality"]["n_perm"]
M["ChronoMod"] = f(r["chronological"]["modality"]["acc"] * 100); M["ChronoFour"] = f(r["chronological"]["4class"]["acc"] * 100)
M["Ncal"] = r["chronological"]["modality"]["n_cal"]; M["Ntest"] = r["chronological"]["modality"]["n_test"]
lc = r["learning_curve"]; ks = sorted(lc, key=int)
if ks:
  M["LCfirstN"] = ks[0]; M["LCfirst"] = f(lc[ks[0]][0] * 100); M["LClastN"] = ks[-1]; M["LClast"] = f(lc[ks[-1]][0] * 100)
for comp, ck in [("AEP N1", "AN"), ("VEP P1", "VP")]:
    rows = r["averaging_detection"][comp]
    for k, v in rows.items():
        M[f"Det{ck}k{k}".replace("1", "One").replace("2", "Two").replace("4", "Four").replace("8", "Eight").replace("6", "Six").replace("3", "Three")] = f(v["det_rate"] * 100, 0)
    # first k reaching >=90% detection
    k90 = next((int(k) for k, v in rows.items() if v["det_rate"] >= 0.9), None)
    M[f"KNinety{ck}"] = k90 if k90 else "--"
    M[f"FAmax{ck}"] = f(max(v["fa_rate"] for k, v in rows.items() if int(k) >= 2) * 100, 0)
    kmax = max(rows, key=int)
    M[f"FAkmax{ck}"] = f(rows[kmax]["fa_rate"] * 100, 0); M[f"Detkmax{ck}"] = f(rows[kmax]["det_rate"] * 100, 0); M["Kmax"] = kmax
    M[f"Detkone{ck}"] = f(rows["1"]["det_rate"] * 100, 0)
ka = r["k_avg_classification"]
for k, v in ka.items():
    M[f"KavgAcc{'ABCDE'[list(ka).index(k)]}"] = f(v[0] * 100)
    M[f"KavgK{'ABCDE'[list(ka).index(k)]}"] = k
M["Decim"] = r["decim"]
cm = np.array(cv["4-class (LA/RA/LV/RV)"]["xDAWN-LDA"]["confusion"])
err = cm.sum() - np.trace(cm)
M["AudConfShare"] = f(100 * (cm[0, 1] + cm[1, 0]) / err, 0)
M["AucAudLatX"] = f(cv["aud. laterality (L vs R)"]["xDAWN-LDA"]["auc_mean"], 3)
M["ClusterFC"] = ", ".join(n.replace("EEG ", "") for n in r["clusters"]["FC"])
M["ClusterO"] = ", ".join(n.replace("EEG ", "") for n in r["clusters"]["O"])
# ROS
base = next(x for x in s if x["task"] == "modality" and x["speed"] == 1.0 and x["chunk_ms"] == 20)
M["RosExcess"] = f(base["excess_ms_mean"]); M["RosExcessSd"] = f(base["excess_ms_sd"]); M["RosExcessP"] = f(base["excess_ms_p95"])
M["RosTotal"] = f(base["total_ms_mean"]); M["RosProc"] = f(base["proc_us_mean"] / 1000, 2)
M["RosAgree"] = f(min(x["agree_offline"] for x in s) * 100, 0)
M["RosNdec"] = sum(x["n_decisions"] for x in s); M["RosNmark"] = sum(x["n_markers"] for x in s)
M["RosMaxExcess"] = f(max(x["excess_ms_max"] for x in s))
M["RosCpuDet"] = f(base["cpu_pct"].get("erp_detector", float("nan")))
M["RosCpuAll"] = f(sum(base["cpu_pct"].values()))
M["RosRss"] = f(sum(base["rss_mb"].values()), 0)
fast = [x for x in s if x["speed"] > 1]
M["RosFastExMin"] = f(min(x["excess_ms_mean"] for x in fast)); M["RosFastExMax"] = f(max(x["excess_ms_mean"] for x in fast))
M["RosFastProc"] = f(min(x["proc_us_mean"] for x in fast) / 1000, 1)
c10 = next(x for x in s if x["chunk_ms"] == 10 and x["speed"] == 1); c40 = next(x for x in s if x["chunk_ms"] == 40)
M["RosExTen"] = f(c10["excess_ms_mean"]); M["RosExForty"] = f(c40["excess_ms_mean"])
M["RosCpuFast"] = f(sum(next(x for x in s if x["speed"] == 10)["cpu_pct"].values()), 0)

with open(os.path.join(out, "numbers.tex"), "w") as fh:
    fh.write("% auto-generated by make_tex_numbers.py -- do not edit\n")
    for k, v in M.items():
        fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

# Table: classification
T = ["\\begin{table}[t]", "\\centering", "\\caption{Single-trial classification (10$\\times$5-fold CV, mean $\\pm$ SD accuracy in \\%; $\\kappa$: Cohen's kappa of xDAWN-LDA).}",
     "\\label{tab:cls}", "\\setlength{\\tabcolsep}{3pt}", "\\footnotesize", "\\begin{tabular}{lccccc}", "\\toprule",
     "Task & Chance & xDAWN-LDA & Cluster-LDA & Template & $\\kappa$ \\\\", "\\midrule"]
names = {"Mod": "AEP vs.\\ VEP", "Four": "4-class", "AudLat": "Aud.\\ L vs.\\ R", "VisLat": "Vis.\\ L vs.\\ R"}
for t, tk in key.items():
    best = max(mkey, key=lambda m: cv[t][m]["acc_mean"])
    cells = []
    for m, mk in mkey.items():
        c = f"{cv[t][m]['acc_mean']*100:.1f}$\\pm${cv[t][m]['acc_sd']*100:.1f}"
        cells.append(f"\\textbf{{{c}}}" if m == best else c)
    T.append(f"{names[tk]} & {r['chance'][t]*100:.1f} & " + " & ".join(cells) + f" & {cv[t]['xDAWN-LDA']['kappa_mean']:.2f} \\\\")
T += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
open(os.path.join(out, "tab_cls.tex"), "w").write("\n".join(T) + "\n")

# Table: ROS 2 timing
T = ["\\begin{table}[t]", "\\centering", "\\caption{End-to-end timing of the ROS 2 pipeline (all nodes on one host). Excess latency is measured from acquisition of the last epoch sample to the published decision.}",
     "\\label{tab:ros}", "\\setlength{\\tabcolsep}{2.5pt}", "\\footnotesize", "\\begin{tabular}{lccccccc}", "\\toprule",
     "Task & Chunk & Speed & Dec./Mark. & Excess (ms) & p95 & Classif. & Agree \\\\",
     " & (ms) & & & mean$\\pm$SD & (ms) & (ms) & (\\%) \\\\", "\\midrule"]
for x in s:
    T.append(f"{'2-class' if x['task']=='modality' else '4-class'} & {x['chunk_ms']} & $\\times${x['speed']:g} & {x['n_decisions']}/{x['n_markers']} & "
             f"{x['excess_ms_mean']:.1f}$\\pm${x['excess_ms_sd']:.1f} & {x['excess_ms_p95']:.1f} & {x['proc_us_mean']/1000:.2f} & {x['agree_offline']*100:.0f} \\\\")
T += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
open(os.path.join(out, "tab_ros.tex"), "w").write("\n".join(T) + "\n")
print(len(M), "macros written")
